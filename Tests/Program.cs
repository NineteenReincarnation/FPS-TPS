using System.Diagnostics;
using System.Globalization;
using Anno.FpsTps;

int checks = 0;
void Check(bool condition, string name)
{
    if (!condition) throw new InvalidOperationException(name);
    checks++;
    Console.WriteLine("PASS " + name);
}

var readout = new TpsReadout();
Check(readout.NeedsRefresh(0, 1, false), "First reading is available immediately");
readout.Update(0, 1, false, 60, 2, 5);
Check(readout.Value == 60 && readout.Target == 60, "Normal native TPS and target");
Check(!readout.NeedsRefresh(0.01, 1, false), "Unchanged speed respects a five-second refresh interval");
Check(readout.NeedsRefresh(0.01, 2, false), "Fast speed bypasses refresh interval on the next draw");
readout.Update(0.01, 2, false, 180, 2, 5);
Check(readout.Value == 180 && readout.Target == 180, "Fast speed updates both numbers without a sample window");
Check(readout.NeedsRefresh(0.02, 3, false), "Superfast speed also bypasses refresh interval");
readout.Update(0.02, 3, false, 360, 2, 5);
Check(readout.Value == 360, "Consecutive rapid speed changes do not hold the old reading");
readout.Update(0.03, 2, false, 180, 10, 5);
Check(readout.Value == 100, "Slow simulation is limited by native tick processing time");
readout.Update(0.04, 1, false, 60, 10, 5);
Check(readout.Value == 60, "Native TPS does not exceed selected target");
Check(readout.NeedsRefresh(0.05, 1, true), "Pause bypasses refresh interval");
readout.Update(0.05, 1, true, 180, 2, 5);
Check(readout.Value == 0 && readout.Target == 0 && readout.TickTime == 0, "Pause clears all stale metrics immediately");
Check(readout.NeedsRefresh(0.06, 2, false), "Resume bypasses refresh interval");
readout.Update(0.06, 2, false, 180, 2, 5);
Check(readout.Value == 180, "Resume has no zero-reading wait");
readout.Update(0.07, 3, false, 360, 0, 5);
Check(readout.Value == 360, "Fresh games with no native tick average display target immediately");
readout.Update(0.08, 3, false, double.NaN, double.PositiveInfinity, 5);
Check(readout.Value == 0 && readout.Target == 0 && readout.TickTime == 0, "Invalid native metrics are finite");
readout.Update(0.08, 3, false, 360, double.PositiveInfinity, 5);
Check(readout.Value == 0, "Invalid execution timing does not report full speed");
Check(readout.NeedsRefresh(0, 3, false), "Clock rewind refreshes cached metrics");
Check(readout.NeedsRefresh(5.08, 3, false), "Configured refresh deadline is respected");

var text = new MetricText();
text.Update(false, 59.5, 60, 0.62, 1, MetricParts.Target | MetricParts.Percent | MetricParts.Cost);
Check(text.Text == "TPS: 59.5 (60)  99%  0.62 ms/t", "Detailed TPS formatting");
int revision = text.Revision;
text.Update(false, 59.501, 60, 0.6201, 1, MetricParts.Target | MetricParts.Percent | MetricParts.Cost);
Check(revision == text.Revision, "Text cache ignores invisible changes");
text.Update(false, 177.2, 180, 0, 0, MetricParts.Percent);
text.Update(false, 177.4, 180, 0, 0, MetricParts.Percent);
Check(text.Text == "TPS: 177  99%", "Percentage refreshes when rounded TPS is unchanged");
text.Update(false, 180, 180, 1.2, 0, MetricParts.Target | MetricParts.Percent | MetricParts.Cost, true);
Check(text.Text == "TPS: 0 (0)", "Pause uses numeric zero without stale target, cost, or text");
text.Update(false, 0, 0, 0, 0, MetricParts.None, true);
Check(text.Text == "TPS: 0", "Pause remains numeric with target hidden");
CultureInfo.CurrentCulture = CultureInfo.GetCultureInfo("fr-FR");
text.Update(true, 60.15, 0, 16.62, 2, MetricParts.Cost);
Check(text.Text == "FPS: 60.15  16.62 ms/f", "Invariant numeric formatting");
text.Update(true, double.NaN, 0, double.PositiveInfinity, 0, MetricParts.Cost);
Check(!text.Text.Contains("NaN") && !text.Text.Contains("Infinity"), "Invalid timing does not leak into labels");

const int iterations = 2_000_000;
for (int i = 0; i < 100_000; i++) readout.Update(i, i % 3, false, 180, 2, 1);
GC.Collect();
long allocated = GC.GetAllocatedBytesForCurrentThread();
long started = Stopwatch.GetTimestamp();
for (int i = 0; i < iterations; i++) readout.Update(i, i % 3, false, 180, 2, 1);
double readoutNs = Stopwatch.GetElapsedTime(started).TotalNanoseconds / iterations;
long readoutBytes = GC.GetAllocatedBytesForCurrentThread() - allocated;
text.Update(true, 60, 0, 16.67, 0, MetricParts.Cost);
for (int i = 0; i < 100_000; i++) text.Update(true, 60, 0, 16.67, 0, MetricParts.Cost);
allocated = GC.GetAllocatedBytesForCurrentThread();
started = Stopwatch.GetTimestamp();
for (int i = 0; i < iterations; i++) text.Update(true, 60, 0, 16.67, 0, MetricParts.Cost);
double cacheNs = Stopwatch.GetElapsedTime(started).TotalNanoseconds / iterations;
long cacheBytes = GC.GetAllocatedBytesForCurrentThread() - allocated;
Check(readoutBytes == 0, "Native TPS calculation allocations = 0 bytes");
Check(cacheBytes == 0, "Unchanged text cache allocations = 0 bytes");
Console.WriteLine($"RESULT {checks} checks passed.");
Console.WriteLine(FormattableString.Invariant($"BENCH native TPS: {readoutNs:F2} ns/call; {readoutBytes} bytes / {iterations:N0} calls"));
Console.WriteLine(FormattableString.Invariant($"BENCH unchanged text: {cacheNs:F2} ns/call; {cacheBytes} bytes / {iterations:N0} calls"));
Console.WriteLine("Core microbenchmarks only; native rendering cost is not included.");
